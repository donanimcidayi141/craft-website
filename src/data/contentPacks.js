/**
 * CraftStudio Faz 4 — Curated Canva-style OOP Content Packs
 * Every preset builds a real editable AST tree (`children: [...]`) so double-click
 * isolation, nested styling, hover animations, function binding, responsive overrides,
 * and 1:1 HTML5/React export work natively on every inner element.
 */

function node({
  id,
  type = 'div',
  name,
  x = 0,
  y = 0,
  width = 120,
  height = 40,
  textContent = '',
  attrs = {},
  style = {},
  animation = undefined,
  events = undefined,
  positionMode = 'normal',
  zIndex = 2,
  children = [],
  ...rest
}) {
  return {
    id,
    type,
    name: name || type,
    x,
    y,
    width,
    height,
    positionMode,
    zIndex,
    ...(textContent !== undefined && textContent !== '' ? { textContent, content: textContent } : {}),
    attrs,
    style: {
      boxSizing: 'border-box',
      ...style,
    },
    ...(animation ? { animation } : {}),
    ...(events ? { events } : {}),
    children,
    ...rest,
  };
}

function navLinkNode(id, text, x, y, width, color = '#d4d4d8', hoverLineColor = '#38bdf8', hoverCls = 'hover-underline-center') {
  return node({
    id,
    type: 'a',
    name: `Link: ${text}`,
    x,
    y,
    width,
    height: 32,
    textContent: text,
    attrs: { href: '#' },
    style: {
      backgroundColor: 'transparent',
      color,
      fontSize: '13px',
      fontWeight: '500',
      display: 'flex',
      alignItems: 'center',
      justifyContent: 'center',
      cursor: 'pointer',
      textDecoration: 'none',
    },
    animation: {
      hoverClassName: hoverCls,
      hoverLineColor,
      hoverLineHeight: 2,
      hoverLineDuration: 0.25,
    },
  });
}

